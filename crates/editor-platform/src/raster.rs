//! Minimal 2-method glyph rasterizer interface + built-in fallback bitmap font.
//!
//! Only single-cluster rasterization sits behind the OS adapter (CoreText on
//! macOS, DirectWrite on Windows, FreeType on Linux). Once rasterized into
//! `editor-render`'s glyph atlas, the OS font engine is never touched on the hot
//! rendering path.

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum FontStyle {
    Mono,
    MonoBold,
    MonoItalic,
    Ui,
    UiBold,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct FontMetrics {
    /// Distance from baseline to top of line in physical pixels (positive).
    pub ascent: f32,
    /// Distance from baseline to bottom of line in physical pixels (positive).
    pub descent: f32,
    /// Extra inter-line spacing in physical pixels.
    pub leading: f32,
    /// Recommended line height in physical pixels (ceil(ascent + descent + leading)).
    pub line_height: u32,
    /// Nominal advance width of `'M'` / `'0'` in physical pixels.
    pub cell_width: f32,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GlyphFormat {
    /// Single-channel coverage alpha (0..=255), tinted with foreground color at composite time.
    Alpha8,
    /// Premultiplied BGRA8 color bitmap (used for color emojis).
    Bgra32,
}

#[derive(Debug, Clone)]
pub struct RasterizedGlyph {
    pub width: u32,
    pub height: u32,
    /// Horizontal offset from pen origin to left edge of bitmap (physical pixels).
    pub bearing_x: i32,
    /// Vertical offset from baseline to top edge of bitmap (positive = above baseline).
    pub bearing_y: i32,
    /// Horizontal pen advance in physical pixels.
    pub advance: f32,
    pub format: GlyphFormat,
    /// Row-major tightly packed pixels (`width * height` for Alpha8, `width * height * 4` for Bgra32).
    pub pixels: Vec<u8>,
}

/// The entire font/text OS boundary: 2 methods.
pub trait GlyphRasterizer {
    fn metrics(&mut self, style: FontStyle, size_px: f32) -> FontMetrics;
    fn rasterize(&mut self, style: FontStyle, size_px: f32, cluster: &str) -> RasterizedGlyph;
}

// ============================================================================
// Pure-Rust Built-in Crisp Bitmap Font Rasterizer (headless tests + fallback)
// ============================================================================

/// Zero-dependency 5x7 crisp bitmap font scaled cleanly to any requested pixel size.
/// Guarantees deterministic, fast, pixel-exact headless rendering in tests.
#[derive(Debug, Default)]
pub struct BuiltinBitmapRasterizer;

impl GlyphRasterizer for BuiltinBitmapRasterizer {
    fn metrics(&mut self, _style: FontStyle, size_px: f32) -> FontMetrics {
        let size = size_px.max(8.0);
        let ascent = (size * 0.80).round();
        let descent = (size * 0.20).round();
        let leading = (size * 0.25).round().max(2.0);
        let line_height = (ascent + descent + leading).ceil() as u32;
        let cell_width = (size * 0.60).round().max(5.0);
        FontMetrics {
            ascent,
            descent,
            leading,
            line_height,
            cell_width,
        }
    }

    fn rasterize(&mut self, style: FontStyle, size_px: f32, cluster: &str) -> RasterizedGlyph {
        let m = self.metrics(style, size_px);
        let first = cluster.chars().next().unwrap_or(' ');
        if first == ' ' || first == '\t' {
            return RasterizedGlyph {
                width: 0,
                height: 0,
                bearing_x: 0,
                bearing_y: 0,
                advance: m.cell_width,
                format: GlyphFormat::Alpha8,
                pixels: Vec::new(),
            };
        }

        let is_wide = is_probable_wide_or_emoji(first, cluster);
        let scale = (size_px / 10.0).round().max(1.0) as u32;
        let base_w = if is_wide { 7u32 } else { 5u32 };
        let base_h = 7u32;
        let w = base_w * scale;
        let h = base_h * scale;
        let mut pixels = vec![0u8; (w * h) as usize];

        let bold = matches!(style, FontStyle::MonoBold | FontStyle::UiBold);
        let pattern = bitmap_5x7(first);

        for gy in 0..base_h {
            let row_bits = pattern[gy as usize];
            for gx in 0..base_w {
                let on = if is_wide {
                    // Draw a tidy rounded badge for emoji/wide glyphs in headless mode.
                    let border = gy == 0 || gy == base_h - 1 || gx == 0 || gx == base_w - 1;
                    let corner = (gy == 0 || gy == base_h - 1) && (gx == 0 || gx == base_w - 1);
                    let eye = gy == 2 && (gx == 2 || gx == 4);
                    let smile = gy == 4 && (gx >= 2 && gx <= 4);
                    (border && !corner) || eye || smile
                } else {
                    let bit = (row_bits >> (4 - gx)) & 1 != 0;
                    let bold_bit = bold && gx > 0 && ((row_bits >> (5 - gx)) & 1 != 0);
                    bit || bold_bit
                };
                if on {
                    for sy in 0..scale {
                        for sx in 0..scale {
                            let px = gx * scale + sx;
                            let py = gy * scale + sy;
                            pixels[(py * w + px) as usize] = 255;
                        }
                    }
                }
            }
        }

        let advance = if is_wide {
            m.cell_width * 2.0
        } else if matches!(style, FontStyle::Ui | FontStyle::UiBold) {
            match first {
                'i' | 'l' | '!' | '.' | ',' | ':' | ';' | '|' | '\'' => (m.cell_width * 0.55).round(),
                'm' | 'w' | 'M' | 'W' => (m.cell_width * 1.15).round(),
                _ => (m.cell_width * 0.90).round(),
            }
        } else {
            m.cell_width
        };

        RasterizedGlyph {
            width: w,
            height: h,
            bearing_x: ((advance - w as f32) * 0.5).floor().max(0.0) as i32,
            bearing_y: h as i32,
            advance,
            format: GlyphFormat::Alpha8,
            pixels,
        }
    }
}

fn is_probable_wide_or_emoji(ch: char, cluster: &str) -> bool {
    let cp = ch as u32;
    cluster.len() > ch.len_utf8()
        || (0x1F300..=0x1FAFF).contains(&cp)
        || (0x2600..=0x27BF).contains(&cp)
        || (0x1F1E6..=0x1F1FF).contains(&cp)
}

